// Hearing words: the words page list and tour, the language panel, playback.
import puppeteer from 'puppeteer-core';
import fs from 'node:fs';
import { quiet } from './quiet.mjs';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--autoplay-policy=no-user-gesture-required'] });
quiet(browser);
const page = await browser.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
const played = [];
page.on('response', (r) => r.url().includes('upload.wikimedia.org') && played.push([r.status(), decodeURIComponent(r.url().split('/').pop())]));
await page.setViewport({ width: 1440, height: 900 });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
fs.mkdirSync('.shots/audio', { recursive: true });
await page.goto(`http://localhost:5173/?lang=${process.argv[2] ?? 'zh-Hans'}#/words/${process.argv[3] ?? 'mother'}`, { waitUntil: 'networkidle0' });
await sleep(3500);
const chips = await page.$$eval('.listen .listen-chip', (els) => els.map((e) => e.textContent.trim()).slice(0, 8));
await page.click('.listen .listen-chip');
await sleep(2500);
await page.screenshot({ path: '.shots/audio/1_words.png' });
await page.click('.listen [data-act=tour]');
await sleep(6000);
await page.screenshot({ path: '.shots/audio/2_tour.png' });
await page.click('.listen [data-act=tour]');
await page.goto(`http://localhost:5173/?lang=${process.argv[2] ?? 'zh-Hans'}#/?sel=${process.argv[4] ?? 'czec1258'}`, { waitUntil: 'networkidle0' });
await sleep(3500);
const panelChips = await page.$$eval('.listen-lang .listen-chip', (els) => els.map((e) => e.textContent.trim()));
if (panelChips.length) await page.click('.listen-lang .listen-chip');
await sleep(2000);
await page.screenshot({ path: '.shots/audio/3_panel.png' });
console.log(JSON.stringify({ chips, panelChips, played, errors }, null, 1));
await browser.close();
